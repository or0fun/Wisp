import AppKit
import CryptoKit

@MainActor final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [Clip] = []
    @Published var paused = false
    @Published var error: String?
    var settings: Settings
    private let disk: DiskStore
    private let pasteboard: NSPasteboard
    private var canPersist = true
    private var timer: Timer?
    private var lastChange: Int
    private var lastPrune = Date.distantPast
    private static let sensitiveTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.typeit4me.clipping"]

    init(disk: DiskStore, settings: Settings, pasteboard: NSPasteboard = .general) {
        self.disk = disk; self.settings = settings; self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
        do { items = try disk.load([Clip].self, from: "clipboard.json") ?? [] }
        catch { self.error = error.localizedDescription + " 清空历史后可重新建立存储。"; canPersist = false }
        prune()
    }
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.captureChanges() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }
    func captureChanges() {
        if Date().timeIntervalSince(lastPrune) > 60 { prune() }
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard settings.clipboardEnabled, !paused else { return }
        let excluded = Set(settings.excludedApps.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespacesAndNewlines) })
        let app = NSWorkspace.shared.frontmostApplication
        guard !excluded.contains(app?.bundleIdentifier ?? "") else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.sensitiveTypes) else { return }
        let source = app?.localizedName ?? "未知应用"
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(Clip(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: "\n"), files: urls.map(\.path), source: source))
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            guard let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation, tiff.count <= 20 * 1024 * 1024,
                  let bitmap = NSBitmapImageRep(data: tiff), let data = bitmap.representation(using: .png, properties: [:]), data.count <= 20 * 1024 * 1024 else { return }
            let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            let filename = "\(hash).png"
            do {
                try disk.write(data, to: disk.images.appendingPathComponent(filename))
                add(Clip(kind: .image, text: "图片 · \(bitmap.pixelsWide) × \(bitmap.pixelsHigh)", imageFile: filename, source: source))
            } catch { self.error = error.localizedDescription }
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= 2 * 1024 * 1024 {
            add(Clip(kind: .text, text: text, source: source))
        }
    }
    private func add(_ clip: Clip) {
        var new = clip
        if let existing = items.first(where: { $0.kind == clip.kind && $0.text == clip.text && $0.imageFile == clip.imageFile && $0.files == clip.files }) {
            new.id = existing.id; new.pinned = existing.pinned
            items.removeAll { $0.id == existing.id }
        }
        items.insert(new, at: 0); prune()
    }
    func prune() {
        lastPrune = Date()
        let cutoff = Date().addingTimeInterval(-Double(settings.retentionDays) * 86400)
        items.removeAll { !$0.pinned && $0.createdAt < cutoff }
        items.sort { $0.pinned == $1.pinned ? $0.createdAt > $1.createdAt : $0.pinned }
        // Pinned items also count toward the hard cap; never allow unbounded storage.
        items = Array(items.prefix(settings.historyLimit))
        var bytes = 0
        items = items.filter { clip in
            let imageBytes = imageURL(for: clip).flatMap { url in (try? FileManager.default.attributesOfItem(atPath: url.path)[.size]) as? NSNumber }?.intValue ?? 0
            let size = clip.text.utf8.count + imageBytes
            guard bytes + size <= 256 * 1024 * 1024 else { return false }
            bytes += size; return true
        }
        guard canPersist else { return }
        persist()
        let used = Set(items.compactMap(\.imageFile))
        if let files = try? FileManager.default.contentsOfDirectory(at: disk.images, includingPropertiesForKeys: nil) {
            for file in files where !used.contains(file.lastPathComponent) { try? FileManager.default.removeItem(at: file) }
        }
    }
    func imageURL(for clip: Clip) -> URL? {
        guard let filename = clip.imageFile, filename == (filename as NSString).lastPathComponent else { return nil }
        return disk.images.appendingPathComponent(filename)
    }
    func restore(_ clip: Clip) throws {
        let board = pasteboard
        let objects: [NSPasteboardWriting]
        switch clip.kind {
        case .text: objects = [clip.text as NSString]
        case .image:
            guard let url = imageURL(for: clip), let image = NSImage(contentsOf: url) else { throw AppError.message("图片文件已不存在。") }
            objects = [image]
        case .files:
            guard clip.files.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) else { throw AppError.message("部分原始文件已移动或删除。历史记录保存的是文件引用。") }
            objects = clip.files.map { NSURL(fileURLWithPath: $0) }
        }
        board.clearContents()
        guard board.writeObjects(objects) else { throw AppError.message("无法写入系统剪贴板。") }
        lastChange = board.changeCount
    }
    func copyText(_ text: String) {
        pasteboard.clearContents(); pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
    }
    func togglePin(_ id: UUID) { if let index = items.firstIndex(where: { $0.id == id }) { items[index].pinned.toggle(); prune() } }
    func delete(_ id: UUID) { items.removeAll { $0.id == id }; prune() }
    func clear() { items.removeAll(); canPersist = true; error = nil; prune() }
    private func persist() {
        do { try disk.save(items, to: "clipboard.json") }
        catch { self.error = error.localizedDescription }
    }
}
